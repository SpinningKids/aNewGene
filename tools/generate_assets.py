#!/usr/bin/env python3
"""Generates the embedded asset headers shared by all platforms.

The song (DUNESHI2.XM) is embedded verbatim. The credits bitmap
(gcbitmap.bmp) is embedded as exactly what the demo uses: its 4bpp pixel
payload (32768 bytes, 2 pixels per byte). Its 16-color palette is the gray
ramp "i * 0x11", so the demo derives the luminance from the pixel index.
The BMP container is stripped out at build time so that the runtime never
parses a bitmapped file.

Run from anywhere:

    py tools/generate_assets.py       (Windows)
    python3 tools/generate_assets.py  (Linux)
"""

import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parent.parent
EMBED_DIR = ROOT / "Resources" / "embedded"
BYTES_PER_LINE = 16


def c_array(name: str, data: bytes) -> str:
    lines = []
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset : offset + BYTES_PER_LINE]
        lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
    return "static const unsigned char %s[] = {\n%s\n};" % (name, "\n".join(lines))


def header_body(comment: str, guard: str, body: str) -> str:
    return (
        "// %s\n"
        "// Generated by tools/generate_assets.py - do not edit by hand.\n"
        "#ifndef %s\n"
        "#define %s\n"
        "\n"
        "%s\n"
        "\n"
        "#endif // %s\n"
    ) % (comment, guard, guard, body, guard)


def bitmap_payload(bmp_path: pathlib.Path) -> bytes:
    """Returns the 4bpp pixel payload from the credits bitmap, which must be
    an uncompressed 4bpp square BMP. The 16-color palette is the gray ramp
    "i * 0x11", so the demo derives the luminance from the pixel index and
    only the payload is embedded."""
    raw = bmp_path.read_bytes()
    if raw[0:2] != b"BM":
        raise ValueError("not a BMP: %s" % bmp_path)
    offbits = struct.unpack_from("<I", raw, 10)[0]
    (bi_size, width, height) = struct.unpack_from("<Iii", raw, 14)
    planes = struct.unpack_from("<H", raw, 26)[0]
    bitcount = struct.unpack_from("<H", raw, 28)[0]
    compression = struct.unpack_from("<I", raw, 30)[0]
    if bi_size != 40 or planes != 1 or compression != 0 or bitcount != 4:
        raise ValueError("expected an uncompressed 4bpp BMP: %s" % bmp_path)
    if width <= 0 or height <= 0 or width != height:
        raise ValueError("expected a square bitmap: %s" % bmp_path)
    table_start = 14 + bi_size  # right after the BITMAPINFOHEADER
    if offbits < table_start + 64:  # after the 16-entry color table
        raise ValueError("color table truncated: %s" % bmp_path)
    stride = (width * 4 + 7) // 8
    pixels = raw[offbits : offbits + stride * height]
    if len(pixels) != stride * height:
        raise ValueError("truncated pixel data: %s" % bmp_path)
    return pixels


def main() -> None:
    EMBED_DIR.mkdir(parents=True, exist_ok=True)

    song = (ROOT / "Resources" / "DUNESHI2.XM").read_bytes()
    payload = bitmap_payload(ROOT / "Resources" / "windows" / "gcbitmap.bmp")

    (EMBED_DIR / "dunesh_2.h").write_text(
        header_body(
            "Song data (DUNESHI2.XM, embedded verbatim; minifmod parses it itself)",
            "ANEWGENE_EMBEDDED_DUNESH_2_H",
            c_array("dixiesmod", song),
        ),
        newline="\n",
    )
    (EMBED_DIR / "gcbitmap.h").write_text(
        header_body(
            "Credits bitmap: 4bpp payload (palette is the gray ramp i * 0x11)",
            "ANEWGENE_EMBEDDED_GCBITMAP_H",
            c_array("gcbitmap_4bpp", payload),
        ),
        newline="\n",
    )

    print("wrote %s (%d bytes of song data)" % ((EMBED_DIR / "dunesh_2.h").relative_to(ROOT), len(song)))
    print("wrote %s (%d bytes of bitmap payload)" % ((EMBED_DIR / "gcbitmap.h").relative_to(ROOT), len(payload)))


if __name__ == "__main__":
    main()
